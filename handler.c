/*
 * Helper to clear a BPF_MAP_TYPE_HASH.
 */
static void clear_hash_map(struct bpf_map *map)
{
    size_t key_size = bpf_map__key_size(map);
    void *keys[128]; // Max entries from map definition
    int max_keys = 128;
    int key_count = 0;
    void *prev_key = NULL;
    
    printf("[Debug]   -> Clearing HASH map (fd %d, key_size %zu)...\n", bpf_map__fd(map), key_size);

    // 1. Collect all keys
    void *current_key = calloc(1, key_size);
    if (!current_key) return;

    // Use bpf_map__get_next_key with correct signature including key_size
    while (bpf_map__get_next_key(map, prev_key, current_key, key_size) == 0) {
        if (key_count < max_keys) {
            keys[key_count] = calloc(1, key_size);
            if (!keys[key_count]) break; // Out of memory
            memcpy(keys[key_count], current_key, key_size);
            key_count++;
        }
        prev_key = current_key;
    }
    free(current_key);

    // 2. Delete all collected keys
    // This function correctly takes key_size
    for (int i = 0; i < key_count; i++) {
        bpf_map__delete_elem(map, keys[i], key_size, BPF_ANY);
        free(keys[i]);
    }
    printf("[Debug]   -> Cleared %d HASH entries.\n", key_count);
}

