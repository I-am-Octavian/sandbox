/*
 * sandbox.c: User-space loader for the curl sandbox.
 *
 * This program:
 * 1. Loads and attaches the eBPF program (sandbox.bpf.c).
 * 2. Resolves whitelisted domains (NET-001) to IPs.
 * 3. Populates the `allowed_ips` eBPF map.
 * 4. Listens for violation logs from the kernel via a ring buffer.
 * 5. Forks and executes 'curl' with the user's arguments.
 * 6. Adds the new curl PID to the `sandboxed_pid` map so the kernel
 * knows which process to trace.
 */
