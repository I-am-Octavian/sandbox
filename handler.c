/*
 * Converts a policy ID enum to a human-readable string.
 */
const char *policy_to_string(enum policy_id p)
{
	switch (p) {
	case POLICY_NET_001_WHITELIST:
		return "NET-001 (Whitelist)";
	case POLICY_NET_002_FAMILY:
		return "NET-002 (Protocol Family)";
	case POLICY_NET_005_PRIVATE_IP:
		return "NET-005 (Private IP)";
	case POLICY_NET_006_PORT:
		return "NET-006 (Port)";
	// NEW: Add FS policies
	case POLICY_FS_001_WRITE_PATH:
		return "FS-001 (Write Path)";
	case POLICY_FS_006_SYS_PATH:
		return "FS-006 (System Path)";
	default:
		return "Unknown";
	}
}

/*
 * Converts an IP address from __u32 (host byte order) to a string.
 */
static char *ip_to_string(__u32 ip)
{
	static __thread char ip_str[INET_ADDRSTRLEN];
	struct in_addr addr = { .s_addr =
					htonl(ip) }; // Convert back to network order for inet_ntop
	inet_ntop(AF_INET, &addr, ip_str, sizeof(ip_str));
	return ip_str;
}

static volatile bool exiting = false;

static void sig_handler(int sig)
{
    exiting = true;
}


/*
 * Callback function to process violation events from the ring buffer.
 */
static int handle_event(void *ctx, void *data, size_t data_sz)
{
	const struct log_event *e = data;

	fprintf(stderr, "\n--- POLICY VIOLATION ---\n");
	fprintf(stderr, "  PID: %d\n", e->pid);
	fprintf(stderr, "  Command: %s\n", e->comm);
	fprintf(stderr, "  Policy: %s\n", policy_to_string(e->policy_id));

	// NEW: Handle different event types
	switch (e->type) {
	case EVENT_NET:
		fprintf(stderr, "  Target: %s:%d\n", ip_to_string(e->net.dest_ip),
			e->net.dest_port);
		break;
	case EVENT_FS:
		fprintf(stderr, "  Target: %s\n", e->fs.path);
		break;
	default:
		fprintf(stderr, "  Target: Unknown event data\n");
	}

	fprintf(stderr, "--------------------------\n");

	return 0;
}

